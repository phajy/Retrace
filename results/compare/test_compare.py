#!/usr/bin/env python3
"""Tests of compare.py on MADE-UP input. No value from F09 is used or needed.

The made-up "published" points are our own baseline lags, re-binned onto geometric bins with a factor of 1.6
(deliberately neither 1.4 nor 2.4), with their error bars set equal to ours. Two made-up "digitisations" add small
reading errors (0.05 of the error bar in lag, 0.002 dex in frequency). Each scenario then changes one thing and
checks that compare.py does what results/compare/PLAN.md (with Amendment 1) says. The outcome under the original
plan (13438ec) is checked on hand-made bins and recorded for every scenario.

Writes test/test_results.json and a demonstration run in test/demo/ (scenario "one bin outside our spread").
Exits with an error if any test fails. Usage (from the repository root):
    python results/compare/test_compare.py
"""
from __future__ import annotations

import csv
import json
import math
import sys
import tempfile
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import compare as cmp  # noqa: E402

TRUE_FACTOR = 1.6
F_START, F_STOP = 1.5e-5, 1.2e-2
Y_RANGE = [-200.0, 400.0]          # made-up plotted lag-axis range: the delta floor is 0.5% of 600 s = 3 s
LAG_NOISE, LOGF_NOISE = 0.05, 0.002
OUT = HERE / "test"


def truth():
    r1 = cmp.load_r1()
    edges = F_START * TRUE_FACTOR ** np.arange(0, 60)
    edges = edges[edges <= F_STOP * TRUE_FACTOR]
    pts = []
    for lo, hi in zip(edges[:-1], edges[1:]):
        b = cmp.per_bin(r1, lo, hi)
        assert b is not None, "every made-up bin must contain a Fourier frequency"
        pts.append({"lo": lo, "hi": hi, "F": math.sqrt(lo * hi), "T": b["lag_s"], "S": b["lag_err_s"],
                    "reliable": b["reliable"], "shift": 0.0})
    return pts


def write_digitisation(folder: Path, pts, seed, hbars=False, drop=None, extra=None, series="main"):
    """extra: {index: lag offset in units of S} applied to this reading only."""
    rng = np.random.default_rng(seed)
    folder.mkdir(parents=True)
    rows, n = [], 0
    for i, p in enumerate(pts):
        nl, nt, nb, nf = rng.normal(0, LAG_NOISE, 3).tolist() + [rng.normal(0, LOGF_NOISE)]
        if drop is not None and i == drop:
            continue
        n += 1
        S = p["S"]
        T = p["T"] + p["shift"] * S + nl * S + (extra or {}).get(i, 0.0) * S
        row = {"point": n, "series": series if i % 2 == 0 else "main", "f_hz": f"{p['F'] * 10 ** nf:.6g}",
               "lag_s": f"{T:.6g}", "lag_top_s": f"{T + S + nt * S:.6g}", "lag_bottom_s": f"{T - S + nb * S:.6g}",
               "f_left_hz": "", "f_right_hz": "", "marker": "filled square", "note": "made-up test input"}
        if hbars:
            row["f_left_hz"] = f"{p['lo'] * 10 ** rng.normal(0, LOGF_NOISE):.6g}"
            row["f_right_hz"] = f"{p['hi'] * 10 ** rng.normal(0, LOGF_NOISE):.6g}"
        rows.append(row)
    with open(folder / "points.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=cmp.POINT_COLUMNS, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    meta = {"digitiser": f"made-up test input, seed {seed}", "source": {"arxiv_id": "none", "version": "none"},
            "method": "generated by test_compare.py", "tool": "test_compare.py",
            "x_axis": {"scale": "log", "plotted_range": [1e-5, 1e-2]},
            "y_axis": {"scale": "linear", "plotted_range": Y_RANGE},
            "had_seen_retrace_result": True, "had_seen_other_digitisation": False}
    (folder / "digitisation.json").write_text(json.dumps(meta, indent=2))


def scenario(tmp: Path, name, pts, out=None, **kw_b):
    a, b = tmp / name / "made-up-a", tmp / name / "made-up-b"
    kw_a = {k: v for k, v in kw_b.items() if k in ("hbars", "series")}
    write_digitisation(a, pts, 1, **kw_a)
    write_digitisation(b, pts, 2, **kw_b)
    return cmp.run([a, b], out or (tmp / name / "out"), label=f"MADE-UP TEST INPUT ({name}), not F09")


def in_hf(p):
    return cmp.HF_RANGE_HZ[0] <= p["F"] < cmp.HF_RANGE_HZ[1]


def pick_bin(pts):
    """A reliable bin with a clearly negative lag near 1e-3 Hz, away from the sign change."""
    c = [i for i, p in enumerate(pts) if p["reliable"] and 9e-4 <= p["F"] <= 2.5e-3 and p["T"] < -p["S"]]
    assert c, "no suitable bin for the disagreement scenarios"
    return c[0]


def pick_low_bin(pts):
    """A reliable bin below 5e-4 Hz (outside the high-frequency range) whose lag is more than 2 sigma above zero."""
    c = [i for i, p in enumerate(pts) if p["reliable"] and p["F"] < 5e-4 and p["T"] > 2 * p["S"]]
    assert c, "no suitable low-frequency bin"
    return c[0]


def main():
    pts = truth()
    k, kl = pick_bin(pts), pick_low_bin(pts)
    results, failures, recorded = {}, [], {}

    def check(name, cond, detail):
        results.setdefault(name, []).append({"check": detail, "passed": bool(cond)})
        if not cond:
            failures.append(f"{name}: {detail}")

    def record(name, s):
        recorded[name] = {"outcome": s["outcome"], "outcome_original_plan": s["outcome_original_plan"],
                          "z_mean": s["baseline"]["high_frequency_mean"].get("z_mean"),
                          "rms_z_F": s["baseline"]["point_by_point"]["rms_z_F"],
                          "max_abs_z_F": s["baseline"]["point_by_point"]["max_abs_z_F"],
                          "rms_limit": s["baseline"]["point_by_point"]["rms_limit"],
                          "abs_z_limit": s["baseline"]["point_by_point"]["abs_z_limit"]}

    with tempfile.TemporaryDirectory() as td:
        tmp = Path(td)

        name = "identical, midpoint edges"
        s = scenario(tmp, name, pts)
        record(name, s)
        b = s["baseline"]
        ptp, hfm = b["point_by_point"], b["high_frequency_mean"]
        check(name, s["self_check"]["passed"], "self-check reproduces lag_frequency.csv")
        check(name, s["self_check"]["segmentation"]["passed"],
              "rebuilding the segments from the light curves reproduces the lags stage's cross spectrum")
        check(name, s["outcome"] == "agrees", f"outcome 'agrees' (got '{s['outcome']}')")
        check(name, s["outcome_original_plan"] == "agrees",
              f"outcome under the original plan 'agrees' (got '{s['outcome_original_plan']}')")
        spread_v = b["reference_spread"]["variants"]
        check(name, len(spread_v) == 8 and all(v["n_bins"] > 0 for v in spread_v.values()),
              f"our own spread uses all 8 reference variants ({len(spread_v)})")
        check(name, ptp["within_our_spread"] is True and np.isfinite(ptp["abs_z_limit"]),
              f"points within our own spread (rms z_F {ptp['rms_z_F']:.2f} <= {ptp['rms_limit']:.2f}, "
              f"max {ptp['max_abs_z_F']:.2f} <= {ptp['abs_z_limit']:.2f})")
        check(name, abs(hfm["z_mean"]) < 0.5, f"high-frequency mean: |z_mean| < 0.5 (got {hfm['z_mean']:+.3f})")
        check(name, abs(s["bin_spacing_A11"]["ratio"] / TRUE_FACTOR - 1) < 0.01,
              f"A-11 side result recovers the spacing 1.6 (got {s['bin_spacing_A11']['ratio']:.4f})")
        check(name, s["digitisation_agreement"]["n_failing"] == 0, "all points pass the agreement check")
        check(name, b["error_bars"]["verdict"] == "similar", f"error bars 'similar' (median rho {b['error_bars']['median_rho']:.3f})")
        alone = {k2: v["outcome"] for k2, v in s["sensitivity"].items() if k2.endswith("alone")}
        check(name, len(alone) == 2 and all(v == "agrees" for v in alone.values()),
              f"each digitisation on its own agrees ({alone})")
        shifts = {k2: (v["outcome"], v["outcome_original_plan"]) for k2, v in s["sensitivity"].items()
                  if k2.startswith("edges shifted")}
        check(name, len(shifts) == 2, f"both edge-shift variants run (outcomes, recorded not tested: {shifts})")
        lim, rms_lim = ptp["abs_z_limit"], ptp["rms_limit"]
        e_mean = math.hypot(hfm["f09"]["error_s"], hfm["delta_s"])

        # exact edges: without reading errors the midpoint rule recovers the true edges
        exact = cmp.f09_edges([{"f_hz": p["F"], "hbar": False} for p in pts])[0]
        check("edge inference", np.allclose(np.log10(exact), np.log10([(p["lo"], p["hi"]) for p in pts]), atol=1e-9),
              "geometric midpoints of geometric bin centres give the true edges")

        name = "horizontal bars"
        s = scenario(tmp, name, pts, hbars=True)
        record(name, s)
        check(name, s["baseline"]["edge_source"] == "horizontal error bars", "edges taken from the bars")
        check(name, s["outcome"] == "agrees", f"outcome 'agrees' (got '{s['outcome']}')")
        sv = s["baseline"]["reference_spread"]["variants"]
        check(name, len(sv) == 8 and all(v["n_bins"] > 0 for v in sv.values()),
              "the reference edge shifts also apply to edges from horizontal bars (all 8 variants run)")

        name = "one bin outside our spread"
        moved = [dict(p) for p in pts]
        moved[kl]["shift"] = lim + 1.0
        s = scenario(tmp, name, moved, out=OUT / "demo")
        record(name, s)
        check(name, s["outcome"] == "agrees, with differences", f"outcome 'agrees, with differences' (got '{s['outcome']}')")
        check(name, s["baseline"]["point_by_point"]["bins_beyond_abs_z_limit"] == [kl + 1],
              f"bin {kl + 1} is the one listed ({s['baseline']['point_by_point']['bins_beyond_abs_z_limit']})")
        check(name, abs(s["baseline"]["high_frequency_mean"]["z_mean"]) < 0.5,
              "the high-frequency mean is unaffected (the moved bin is below 7e-4 Hz)")

        for name, nz, want in (("high-frequency mean 1.5 off", 1.5, "agrees, with differences"),
                               ("high-frequency mean 3 off", 3.0, "does not agree")):
            moved = [dict(p) for p in pts]
            for p in moved:
                if in_hf(p):
                    p["shift"] = -nz * e_mean / p["S"]
            s = scenario(tmp, name, moved)
            record(name, s)
            zm = s["baseline"]["high_frequency_mean"]["z_mean"]
            check(name, abs(abs(zm) - nz) < 0.25, f"|z_mean| close to {nz} (got {zm:+.3f})")
            check(name, s["outcome"] == want, f"outcome '{want}' (got '{s['outcome']}')")
            check(name, any("high-frequency weighted mean" in r for r in s["reasons"]),
                  f"the high-frequency mean is named in the reasons ({s['reasons']})")

        name = "opposite signs in one bin"
        moved = [dict(p) for p in pts]
        moved[kl]["shift"] = -2 * pts[kl]["T"] / pts[kl]["S"]
        s = scenario(tmp, name, moved)
        record(name, s)
        check(name, s["outcome"] == "does not agree", f"outcome 'does not agree' (got '{s['outcome']}')")
        check(name, any("opposite signs" in r and f"[{kl + 1}]" in r for r in s["reasons"]),
              f"opposite signs named for bin {kl + 1} ({s['reasons']})")

        name = "digitisers disagree on one point"
        s = scenario(tmp, name, pts, extra={k: 0.6})
        record(name, s)
        ag = s["digitisation_agreement"]
        bad = [c for c in ag["points"] if not c["passes"]]
        bk = next(x for x in s["baseline"]["bins"] if abs(math.log10(x["f09_f_hz"] / pts[k]["F"])) < 0.01)
        ck = next(c for c in ag["points"] if abs(math.log10(c["f_hz"] / pts[k]["F"])) < 0.01)
        want = max(abs(ck["dlag_s"]) / 2, ag["floor_s"])
        check(name, len(bad) == 1, f"exactly one point fails the agreement check (got {len(bad)})")
        check(name, bad and abs(bad[0]["dlag_over_S"] + 0.6) < 0.15,
              f"it is the point read 0.6 S apart (got {bad[0]['dlag_over_S'] if bad else None:.3f} S)")
        check(name, abs(bk["delta_s"] - want) < 1e-9,
              f"its delta is half the difference or the floor, whichever is larger ({bk['delta_s']:.3f} s; "
              f"half the difference {abs(ck['dlag_s']) / 2:.3f} s, floor {ag['floor_s']:.3f} s)")
        check(name, s["outcome"] == "agrees", f"outcome 'agrees' (got '{s['outcome']}')")

        name = "one digitiser misses a point"
        s = scenario(tmp, name, pts, drop=k)
        record(name, s)
        st = s["baseline"]["n_bins_by_status"]
        check(name, s["digitisation_agreement"]["unmatched"]["made-up-a"] == [k + 1],
              f"the missed point is listed as unmatched ({s['digitisation_agreement']['unmatched']})")
        check(name, st.get("found by one digitiser only") == 1, f"its bin is not compared ({st})")
        check(name, s["outcome"] == "agrees", f"outcome 'agrees' (got '{s['outcome']}')")

        for name, kw in (("two series", {"series": "inset"}),):
            try:
                scenario(tmp, name, pts, **kw)
                check(name, False, "stops when a digitisation has more than one series")
            except SystemExit as e:
                check(name, "more than one series" in str(e), "stops when a digitisation has more than one series")
        try:
            cmp.run([tmp / "identical, midpoint edges" / "made-up-a"], tmp / "one")
            check("one digitisation", False, "stops with only one digitisation")
        except SystemExit as e:
            check("one digitisation", "exactly two" in str(e), "stops with only one digitisation")

    # the classification rules on their own, with hand-made bins
    def mk(zf, ours, oerr, f09, ferr, n=1):
        return {"bin": n, "z_F": zf, "ours_lag_s": ours, "ours_lag_err_s": oerr, "f09_lag_s": f09, "f09_err_S_s": ferr}

    def pp(within):
        return {"within_our_spread": within, "rms_z_F": 0.5, "max_abs_z_F": 0.5, "rms_limit": 0.6, "abs_z_limit": 1.0,
                "bins_beyond_abs_z_limit": []}
    ok = {"status": "same or adjacent", "detail": ""}
    far = {"status": "far", "detail": ""}
    und = {"status": "undetermined", "detail": "2 and 1"}
    plain = [mk(0.5, -20, 5, -22, 5)]
    amended = [
        ("agrees", plain, ok, 0.5, True),
        ("agrees, with differences", plain, ok, 1.5, True),
        ("agrees, with differences", plain, ok, 0.5, False),
        ("does not agree", plain, ok, 2.5, True),
        ("does not agree", plain, ok, -2.5, True),
        ("does not agree", [mk(0.5, 15, 5, -15, 5)], ok, 0.5, True),     # opposite signs, both > 2 sigma
        ("agrees", [mk(0.5, 3, 5, -3, 5)], ok, 0.5, True),               # opposite signs, neither > 2 sigma
        ("does not agree", plain, far, 0.5, True),
        ("not covered by the plan", plain, und, 0.5, True),
        ("agrees, with differences", plain, und, 0.5, False),
        ("not covered by the plan", plain, ok, None, True),
        ("not covered by the plan", plain, ok, 0.5, None),
        ("agrees, with differences", plain, ok, 1.5, None),
        ("not covered by the plan", [], ok, 0.5, True),
    ]
    for want, bins, sc, zm, within in amended:
        got, why = cmp.classify(bins, sc, {"z_mean": zm}, pp(within))
        check("classification rule (amended)", got == want,
              f"{want!r} for z_mean={zm}, within our spread={within}, sign change {sc['status']}, "
              f"bins {[(x['ours_lag_s'], x['f09_lag_s']) for x in bins]} (got {got!r})")
    original = [
        ("agrees", [mk(0.5, -20, 5, -22, 5)], ok),
        ("agrees, with differences", [mk(1.5, -20, 5, -27, 5)], ok),
        ("does not agree", [mk(2.5, -20, 5, -32, 5)], ok),
        ("does not agree", [mk(0.5, 15, 5, -15, 5)], ok),
        ("agrees", [mk(0.5, 3, 5, -3, 5)], ok),
        ("does not agree", [mk(0.5, -20, 5, -22, 5)], far),
        ("not covered by the plan", [mk(0.5, -20, 5, -22, 5)], und),
        ("agrees, with differences", [mk(1.5, -20, 5, -27, 5)], {"status": "undetermined", "detail": ""}),
    ]
    for want, bins, sc in original:
        got, why = cmp.classify_original(bins, sc)
        check("classification rule (original plan)", got == want,
              f"{want!r} for z_F={bins[0]['z_F']}, ours {bins[0]['ours_lag_s']}, F09 {bins[0]['f09_lag_s']}, "
              f"sign change {sc['status']} (got {got!r})")

    # Measurement, not a test: how far binning alone moves z_F. Exact made-up points (our own values on the true
    # 1.6x bins, no reading errors, delta = 3 s) compared with our spectrum on bins shifted by a fraction of a width.
    r1 = cmp.load_r1()
    exact_pts = [{"points": {"exact": i + 1}, "usable": True, "f_hz": p["F"], "lag_s": p["T"],
                  "lag_top_s": p["T"] + p["S"], "lag_bottom_s": p["T"] - p["S"], "f_left_hz": math.nan,
                  "f_right_hz": math.nan, "S": p["S"], "asym_s": 0.0, "delta_s": 3.0, "delta_top_s": 3.0,
                  "delta_bottom_s": 3.0, "hbar": False} for i, p in enumerate(pts)]
    binning = {}
    for sh in (0.05, 0.1, 0.25):
        for sgn in (-1, 1):
            ev = cmp.evaluate(r1, exact_pts, sgn * sh)
            c = [b for b in ev["bins"] if b["status"] == "counts"]
            binning[f"{sgn * sh:+.2f}"] = {"outcome": ev["outcome"], "outcome_original_plan": ev["outcome_original_plan"],
                                           "max_abs_z_F": ev["max_abs_z_F"],
                                           "z_mean": ev["high_frequency_mean"].get("z_mean"),
                                           "z_F": {f"{b['f09_f_hz']:.3g}": b["z_F"] for b in c}}

    OUT.mkdir(exist_ok=True)
    summary = {"input": "MADE-UP: our own baseline lags on 1.6x geometric bins with reading errors; no F09 values",
               "made_up_bins": len(pts), "bin_near_1e-3_hz": k + 1, "low_frequency_bin": kl + 1,
               "passed": not failures, "failures": failures, "tests": results,
               "outcomes_by_scenario": recorded,
               "binning_sensitivity_measurement": {
                   "what": "our own spectrum compared with itself (exact made-up points on the true 1.6x bins, "
                           "S = our error, delta = 3 s) after shifting all bin edges by the given fraction of a bin "
                           "width in log frequency. Not a test: it shows how far binning alone moves z_F and z_mean, "
                           "and the outcome under the amended and the original plan.",
                   "shifts": binning}}
    for key, v in binning.items():
        print(f"binning only, edges shifted {key} bin: max |z_F| = {v['max_abs_z_F']:.2f}, z_mean {v['z_mean']:+.2f} "
              f"({v['outcome']}; original plan: {v['outcome_original_plan']})")
    for key, v in recorded.items():
        print(f"{key}: {v['outcome']} (original plan: {v['outcome_original_plan']})")
    json.dump(cmp.clean(summary), open(OUT / "test_results.json", "w"), indent=2)
    for name, cs in results.items():
        for c in cs:
            print(f"{'PASS' if c['passed'] else 'FAIL'}  {name}: {c['check']}")
    if failures:
        raise SystemExit(f"{len(failures)} test(s) FAILED")
    print(f"all {sum(len(v) for v in results.values())} checks passed")


if __name__ == "__main__":
    main()
